def analyze_for_contra_x(changelog_raw, tag):
    """
    GitHub release changelogini Contra X o'yinchisi nuqtai nazaridan
    sodda va amaliy tarzda tahlil qiladi.
    """

    prompt = f"""
Ты — опытный игрок C&C Generals Zero Hour: Contra X.
Твоя задача — анализировать изменения из GitHub release так,
чтобы обычный игрок Contra X сразу понимал, что изменилось
и как это может ощущаться в игре.

RELEASE: {tag}

CHANGELOG:
{changelog_raw}

ВАЖНЫЕ ПРАВИЛА:

1. Используй ТОЛЬКО информацию из CHANGELOG.
   Ничего не выдумывай.

2. Не пиши как программист или разработчик.
   Пиши как игрок Generals/Contra X, который объясняет
   обновление другим игрокам.

3. Не делай сухой перевод changelog.
   Нужно ОБЪЯСНИТЬ смысл изменения для игры.

4. Если изменение техническое и игрок почти не заметит его,
   так и скажи:
   "Для обычного игрока влияние небольшое"
   или
   "Это в основном техническое изменение."

5. Если изменение действительно может повлиять на игру,
   объясни КАК именно:
   - движение юнитов
   - атака
   - защита
   - экономика
   - строительство
   - AI
   - баланс
   - управление
   - карты
   - стабильность игры
   - сетевые игры

6. Не утверждай, что изменение усиливает или ослабляет
   GLA/USA/China, если в changelog для этого нет основания.

7. Если изменение связано с конкретной фракцией или юнитом,
   обязательно объясни это простыми словами.

8. Особенно учитывай игру 3v3 и 4v4.
   Если изменение может быть заметно именно в командной игре,
   отдельно укажи это.

9. Не нужно каждый раз писать про GLA, USA и China.
   Указывай только те фракции, которых реально касается изменение.

10. Не используй сложные технические термины без объяснения.

11. Не преувеличивай.
   Если невозможно точно определить влияние изменения
   только по changelog, напиши:
   "Точное влияние на gameplay по changelog определить нельзя."

12. Самое важное — отделяй ФАКТ от ПРЕДПОЛОЖЕНИЯ.
   Если changelog прямо говорит об изменении — это факт.
   Если ты объясняешь возможное влияние на gameplay,
   используй формулировки:
   "может повлиять",
   "вероятно будет заметно",
   "возможно улучшит".

ФОРМАТ ОТВЕТА:

🎮 Contra X — {tag}

📌 Главное:
Коротко объясни 2–4 самых важных изменения
простым языком.

⚔️ Что изменится в игре:
Объясни практическое влияние изменений
на обычного игрока.

🟢 GLA:
Пиши только если изменение действительно касается GLA.

🔵 USA:
Пиши только если изменение действительно касается USA.

🔴 China:
Пиши только если изменение действительно касается China.

👥 3v3 / 4v4:
Пиши только если изменение может иметь значение
для командной игры.

💡 Простыми словами:
В конце дай очень короткое объяснение:
что игроку Contra X реально нужно знать об этом обновлении.

Если changelog содержит много мелких технических изменений,
не перечисляй их все.
Выбери только те, которые имеют значение для игрока.

Не используй Markdown-таблицы.
Не пиши длинное вступление.
Не повторяй changelog дословно.
Ответ должен быть компактным, понятным и полезным игроку.
Ответ дай НА РУССКОМ ЯЗЫКЕ.
"""

    payload = {
        "contents": [
            {
                "parts": [
                    {
                        "text": prompt
                    }
                ]
            }
        ]
    }

    for attempt in range(3):
        try:
            response = requests.post(
                GEMINI_URL,
                json=payload,
                timeout=60
            )

            if response.status_code == 200:
                data = response.json()

                text = (
                    data.get("candidates", [{}])[0]
                    .get("content", {})
                    .get("parts", [{}])[0]
                    .get("text", "")
                    .strip()
                )

                if text:
                    return text

        except Exception as e:
            print(f"Gemini attempt {attempt + 1} failed: {e}")

        if attempt < 2:
            time.sleep(5)

    return None
